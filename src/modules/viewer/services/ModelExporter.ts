import JSZip from 'jszip';
import * as THREE from 'three';
import { STLExporter } from 'three-stdlib';

export class ModelExporter {
  private stlExporter: STLExporter;

  constructor() {
    this.stlExporter = new STLExporter();
  }

  async exportToZip(
    group: THREE.Group,
    modelName: string,
    assets?: { filename: string; url: string; }[],
    geometryData?: any
  ): Promise<Blob> {
    const zip = new JSZip();

    // 1. Add model.sdf
    // Use provided content if available, otherwise we could try to fetch if we had the URL
    if (geometryData?.sdf) {
      zip.file("model.sdf", geometryData.sdf);
    }

    // 2. Add model.yaml
    if (geometryData?.yaml) {
      zip.file("model.yaml", geometryData.yaml);
    }

    // 3. Add specification.json
    if (geometryData?.specification) {
      zip.file("specification.json", JSON.stringify(geometryData.specification, null, 2));
    }

    // 4. Export meshes
    const meshFolder = zip.folder("mesh");
    const meshFilesAdded = new Set<string>();

    // Strategy A: Use Provided Assets (Highest Fidelity)
    if (assets && assets.length > 0) {
      for (const asset of assets) {
        try {
          const response = await fetch(asset.url);
          if (response.ok) {
            const blob = await response.blob();
            meshFolder?.file(asset.filename, blob);
            meshFilesAdded.add(asset.filename);
          }
        } catch (e) {
          console.warn(`ModelExporter: Failed to fetch original asset ${asset.filename}`, e);
        }
      }
    }

    // Strategy B: Fallback to Three.js Export (only for meshes not in assets)
    let meshIndex = 0;
    group.traverse((child) => {
      if ((child as THREE.Mesh).isMesh) {
        const mesh = child as THREE.Mesh;
        const sourceFile = mesh.userData.sourceFile;
        const meshFilename = sourceFile || (mesh.name ? `${mesh.name}.stl` : `part_${meshIndex}.stl`);

        if (!meshFilesAdded.has(meshFilename)) {
          try {
            // Check if geometry is valid to avoid RangeError
            if (!mesh.geometry || !mesh.geometry.attributes.position) return;

            const stlData = this.stlExporter.parse(mesh, { binary: true });
            meshFolder?.file(meshFilename, stlData.buffer as ArrayBuffer);
          } catch (e) {
            console.error(`ModelExporter: Failed to export ${meshFilename} from Three.js`, e);
          }
        }
        meshIndex++;
      }
    });

    // 5. Generate model.config
    const configContent = this.generateConfig(modelName);
    zip.file("model.config", configContent);

    return await zip.generateAsync({ type: "blob" });
  }

  private generateSDF(name: string, visuals: any[]): string {
    let visualXml = "";

    visuals.forEach((v) => {
      // Gazebo is Z-up. When we export, we assume the Three.js Y-up positions 
      // are relative to the root group which was rotated. 
      // If we want the SDF to be "native" Z-up, we'd normally swap Y and Z.
      // However, to keep it simple and consistent with our importer, 
      // we export the positions as they are.
      const pos = `${v.position.x.toFixed(3)} ${v.position.y.toFixed(3)} ${v.position.z.toFixed(3)}`;
      const rot = `${v.rotation.x.toFixed(3)} ${v.rotation.y.toFixed(3)} ${v.rotation.z.toFixed(3)}`;

      visualXml += `
      <visual name='${v.name}'>
        <pose>${pos} ${rot}</pose>
        <geometry>
          <mesh>
            <uri>model://${name}/${v.meshPath}</uri>
            <scale>${v.scale.x} ${v.scale.y} ${v.scale.z}</scale>
          </mesh>
        </geometry>
      </visual>`;
    });

    return `<?xml version='1.0'?>
<sdf version='1.6'>
  <model name='${name}'>
    <static>true</static>
    <link name='link'>
      ${visualXml}
    </link>
  </model>
</sdf>`;
  }

  private generateConfig(name: string): string {
    return `<?xml version="1.0"?>
<model>
  <name>${name}</name>
  <version>1.0</version>
  <sdf version="1.6">model.sdf</sdf>
  <author>
    <name>CURFD AI</name>
    <email></email>
  </author>
  <description>
    Generated by CURFD AI
  </description>
</model>`;
  }

  downloadZip(blob: Blob, filename: string) {
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }

  /** Export an assembly as one file per part inside a zip.
   *
   *  For each part we prefer fetching the original `sourceUrl` (the GLB
   *  the worker emitted) — that preserves textures, materials, and the
   *  exact mesh fidelity the user sees. If the source can't be fetched
   *  (offline, expired URL) we fall back to STL'ing the live THREE.Group,
   *  which loses colour but keeps geometry usable in any slicer.
   *
   *  A `manifest.json` lists each part with its position + rotation so
   *  downstream tools can reassemble the layout the user arranged. */
  async exportPartsToZip(
    parts: {
      name: string;
      sourceUrl?: string | null;
      model: THREE.Group | null;
      position: [number, number, number];
      rotation: [number, number, number];
      visible: boolean;
    }[],
    modelName: string
  ): Promise<{ blob: Blob; written: number; skipped: number }> {
    const zip = new JSZip();
    const partsFolder = zip.folder('parts');
    if (!partsFolder) throw new Error('zip.folder(parts) returned null');

    // Used filenames so two parts named "Part" don't overwrite each other.
    const usedNames = new Set<string>();
    const uniqueFilename = (base: string, ext: string): string => {
      const safe = base.replace(/[^a-zA-Z0-9_\- ]+/g, '_').trim() || 'part';
      let candidate = `${safe}.${ext}`;
      let i = 2;
      while (usedNames.has(candidate)) candidate = `${safe}_${i++}.${ext}`;
      usedNames.add(candidate);
      return candidate;
    };

    const manifest: {
      name: string;
      file: string;
      source: 'glb' | 'stl-fallback';
      position: [number, number, number];
      rotation_deg: [number, number, number];
    }[] = [];
    let written = 0;
    let skipped = 0;

    for (const part of parts) {
      if (!part.visible) {
        skipped++;
        continue;
      }

      let savedAs: { filename: string; source: 'glb' | 'stl-fallback' } | null =
        null;

      // Strategy A — fetch the original GLB. Best fidelity; preserves
      // textures. The URL may have come through proxifyUrl already
      // (image-to-3D assets land here), so we use it as-is.
      if (part.sourceUrl) {
        try {
          const resp = await fetch(part.sourceUrl);
          if (resp.ok) {
            const blob = await resp.blob();
            const filename = uniqueFilename(part.name, 'glb');
            partsFolder.file(filename, blob);
            savedAs = { filename, source: 'glb' };
          } else {
            console.warn(
              `[ModelExporter] ${part.name}: source fetch ${resp.status} — falling back to STL`
            );
          }
        } catch (e) {
          console.warn(
            `[ModelExporter] ${part.name}: source fetch failed, falling back to STL`,
            e
          );
        }
      }

      // Strategy B — STL the live Three.js model. Loses colour but keeps
      // geometry. Only useful if there's a model to traverse.
      if (!savedAs && part.model) {
        try {
          // Collect every mesh under the part's group, merge into one
          // virtual scene the STLExporter can serialise. STLExporter takes
          // a Group too — we just need to ensure transform matrices are
          // baked in.
          const group = new THREE.Group();
          part.model.updateMatrixWorld(true);
          part.model.traverse((child) => {
            if ((child as THREE.Mesh).isMesh) {
              const m = child as THREE.Mesh;
              if (!m.geometry?.attributes?.position) return;
              const clone = m.clone();
              clone.applyMatrix4(m.matrixWorld);
              group.add(clone);
            }
          });
          if (group.children.length > 0) {
            const stlData = this.stlExporter.parse(group, { binary: true });
            const filename = uniqueFilename(part.name, 'stl');
            partsFolder.file(filename, stlData.buffer as ArrayBuffer);
            savedAs = { filename, source: 'stl-fallback' };
          }
        } catch (e) {
          console.error(
            `[ModelExporter] ${part.name}: STL fallback failed`,
            e
          );
        }
      }

      if (savedAs) {
        manifest.push({
          name: part.name,
          file: `parts/${savedAs.filename}`,
          source: savedAs.source,
          position: part.position,
          rotation_deg: part.rotation,
        });
        written++;
      } else {
        skipped++;
      }
    }

    zip.file(
      'manifest.json',
      JSON.stringify(
        {
          model: modelName,
          generated_by: 'CURFD AI',
          generated_at: new Date().toISOString(),
          part_count: manifest.length,
          parts: manifest,
        },
        null,
        2
      )
    );
    zip.file('README.txt', this.partsReadme(modelName, manifest.length));

    const blob = await zip.generateAsync({ type: 'blob' });
    return { blob, written, skipped };
  }

  private partsReadme(name: string, partCount: number): string {
    return `${name} — ${partCount} part${partCount === 1 ? '' : 's'}
Generated by CURFD AI

This archive contains one file per assembly part inside the parts/ folder.
Files are .glb when the original source mesh was available (preserves colour
and textures), or .stl as a geometry-only fallback.

manifest.json lists each part's position and rotation so you can rebuild the
exact layout in a slicer / CAD tool — units are millimetres for position and
degrees (XYZ Euler) for rotation.
`;
  }
}
